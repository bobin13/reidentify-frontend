CREATE TABLE IF NOT EXISTS user_activities (
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  activity_id bigint NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, activity_id)
);

CREATE TABLE IF NOT EXISTS group_activities (
  group_id uuid NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  activity_id bigint NOT NULL REFERENCES activities(activity_id) ON DELETE RESTRICT,
  PRIMARY KEY (group_id, activity_id)
);

CREATE TABLE IF NOT EXISTS group_messages (
  group_id uuid NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  id text NOT NULL,
  sender_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  sender_name text NOT NULL,
  text text NOT NULL,
  original_text text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  edited_at timestamptz,
  deleted boolean NOT NULL DEFAULT false,
  sequence bigint NOT NULL,
  revision bigint NOT NULL,
  PRIMARY KEY (group_id, id),
  UNIQUE (group_id, sequence)
);
CREATE INDEX IF NOT EXISTS group_messages_revision_idx
  ON group_messages (group_id, revision);

CREATE TABLE IF NOT EXISTS group_hidden_members (
  group_id uuid NOT NULL,
  user_id uuid NOT NULL,
  hidden_user_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (group_id, user_id, hidden_user_id),
  FOREIGN KEY (group_id, user_id)
    REFERENCES group_memberships(group_id, user_id) ON DELETE CASCADE,
  FOREIGN KEY (group_id, hidden_user_id)
    REFERENCES group_memberships(group_id, user_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS contact_blocks (
  owner_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  target_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (owner_id, target_id),
  CHECK (owner_id <> target_id)
);
CREATE INDEX IF NOT EXISTS contact_blocks_target_idx ON contact_blocks (target_id);

CREATE TABLE IF NOT EXISTS group_reports (
  id text PRIMARY KEY,
  group_id uuid NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  reporter_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  member_id uuid REFERENCES users(id) ON DELETE SET NULL,
  message_id text,
  message_text text,
  reason text NOT NULL CHECK (reason IN ('Harassment', 'Scam or spam', 'Private information', 'Other')),
  details text NOT NULL DEFAULT '',
  latest_details text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'open',
  created_at timestamptz NOT NULL DEFAULT now(),
  last_reported_at timestamptz
);
CREATE INDEX IF NOT EXISTS group_reports_group_created_idx
  ON group_reports (group_id, created_at DESC);

CREATE TABLE IF NOT EXISTS group_events (
  id text PRIMARY KEY,
  group_id uuid NOT NULL REFERENCES community_groups(id) ON DELETE CASCADE,
  creator_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  request_id text NOT NULL,
  title text NOT NULL,
  location text NOT NULL,
  description text NOT NULL DEFAULT '',
  latitude double precision NOT NULL,
  longitude double precision NOT NULL,
  map_cell text,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'published'
    CHECK (status IN ('published', 'cancelled')),
  interests text[] NOT NULL DEFAULT '{}',
  time_zone text NOT NULL DEFAULT 'America/Toronto',
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (group_id, request_id),
  CHECK (latitude BETWEEN -90 AND 90),
  CHECK (longitude BETWEEN -180 AND 180),
  CHECK (ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS group_events_group_start_idx
  ON group_events (group_id, starts_at) WHERE status = 'published';
CREATE INDEX IF NOT EXISTS group_events_map_cell_idx
  ON group_events (map_cell) WHERE status = 'published';

CREATE TABLE IF NOT EXISTS direct_conversations (
  id text PRIMARY KEY,
  user_low uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_high uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_message_id text,
  last_message_text text,
  last_message_sender_id uuid REFERENCES users(id) ON DELETE SET NULL,
  CHECK (user_low < user_high),
  UNIQUE (user_low, user_high)
);
CREATE INDEX IF NOT EXISTS direct_conversations_updated_idx
  ON direct_conversations (updated_at DESC);

CREATE TABLE IF NOT EXISTS direct_messages (
  conversation_id text NOT NULL REFERENCES direct_conversations(id) ON DELETE CASCADE,
  id text NOT NULL,
  sender_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  text text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversation_id, id)
);
CREATE INDEX IF NOT EXISTS direct_messages_created_idx
  ON direct_messages (conversation_id, created_at DESC, id);

CREATE TABLE IF NOT EXISTS direct_conversation_reads (
  conversation_id text NOT NULL REFERENCES direct_conversations(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  last_read_at timestamptz,
  last_read_message_id text,
  PRIMARY KEY (conversation_id, user_id)
);

